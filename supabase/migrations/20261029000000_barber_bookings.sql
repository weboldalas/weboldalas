-- Barber booking concept (Vágvölgyi Ákos): appointments for the /barber site.
-- Accessed only from the Next.js server with the service-role key; RLS is on
-- with no policies so the anon key cannot read customer data.

create extension if not exists btree_gist;

create table if not exists public.barber_bookings (
  id uuid primary key default gen_random_uuid(),
  token text not null unique, -- generated by the app (base64url, 144 bits)
  service_id text not null,
  service_name text not null,
  duration_min integer not null check (duration_min > 0),
  price_huf integer not null check (price_huf >= 0),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  blocks_until timestamptz not null,
  customer_name text not null,
  customer_email text,
  customer_phone text,
  note text,
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  source text not null default 'online' check (source in ('online', 'admin')),
  created_at timestamptz not null default now(),
  cancelled_at timestamptz,
  check (ends_at > starts_at and blocks_until >= ends_at)
);

-- The real double-booking guard: two confirmed appointments can never overlap,
-- even if two customers submit the same slot at the same moment.
alter table public.barber_bookings
  drop constraint if exists barber_bookings_no_overlap;
alter table public.barber_bookings
  add constraint barber_bookings_no_overlap
  exclude using gist (tstzrange(starts_at, blocks_until, '[)') with &&)
  where (status = 'confirmed');

create index if not exists barber_bookings_starts_at_idx on public.barber_bookings (starts_at);

alter table public.barber_bookings enable row level security;
